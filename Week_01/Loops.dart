void main() {

    // Loop is used to repeat a block of code multiple times until a certain condition is met.

    // For loop is used to execute a block of code for specific number of times.
for(int a = 1; a <= 5; a++){           
   print(a);
 }
 
 // While loop is used to execute a block of code repeatedly as long as a certain condition is true.
  int b = 5;         
while(b <= 10){      // condition part 
   print(b);
   b++;
 }

 // Do-while loop runs at least once, then checks the condition.
  int c = 10;
do{
   print(c);
   c++;
  } while(c <= 15);
}
 


