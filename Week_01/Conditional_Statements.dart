void main() {
String trafficLight = "yellow";

   // :Program on Traffic Lights.Using if,else if and else statements.

if (trafficLight == "green") {
    print("Car is going");            // when light green print this statement.
                             
} else if (trafficLight == "red") {
    print("Car is stop");              // when light red print this statement.
    
 } else if (trafficLight == "yellow") {
    print("Car is waiting");            // when light yellow print this statement. 
             
} else {
    print("Light is broken");           // when all conditions are false print this statement. 
  }

}  
 